
# Python executa codul linie cu linie -> (este un limbaj interpretat)
# Intai se defineste variabila si apoi o folosesc ( nu invers)

# print(variabila) - da eroare daca ordinea este gresita

variabila = 234
print(variabila)

# Variabilele in Python pot sa schimba tipul de date (loosly typed)
variabila = True
print(variabila)

# Variabila este Case Sensitive
VARIABILA = 10000
print(VARIABILA)

# Exista conventia - ca variabila sa fie cu litere mici
print(variabila)

# Exista conventia - constantele sa fie definite cu litere mari
VARIABILA = "salutare"
print(VARIABILA)

