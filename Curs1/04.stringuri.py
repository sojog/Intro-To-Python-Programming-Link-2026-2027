
# Stringurile pot fi cu ghilimele duble sau simple
print("hello")
print('hello')

print("hello << Aici e un text ca un fel de ghilimele >> ")

print("hello 'Aici e un text ca un fel de ghilimele' ")

print('hello "Aici e un text ca un fel de ghilimele" """"""""""""""""" ')

print("""

        Acestea sunt ghilimele triple

        
        Sunt folosite pentru documentatie sau texte multilinie
""")

print('''

        Acestea sunt ghilimele triple

        
        Sunt folosite pentru documentatie sau texte multilinie
''')

##     \ este un caracter de ESCAPING
print(' In interiorul unui string vreau sa folosesc \' acelasi tip ghilimele ca si stringul')


##     \n   - reprezina new line

print( "  m \n \n\n\n\n\n\n\n o p q   " )