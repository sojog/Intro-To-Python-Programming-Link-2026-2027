## Python face operatii matematice

## Adunare
print(1 + 1000)
2 + 6

## Scadere
print(20 - 3)

## Inmultire
print(2 * 5)

## Impartire
print(10 / 2)
print(11 / 2)

## Impartire cu partea intreaga
print(10000 // 2)
print(10001 // 2)


## Ridicare la putere
print(9 ** 2)

## Impartirea cu rest
## 11 : 3 = 3, rest 2

## Catul impartirii lui 11 la 3
print(11 // 3)

## Restul impartirii lui 11 la 3
print(11 % 3)


